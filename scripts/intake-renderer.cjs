const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');

async function verify({window,core,root,fixture}) {
  const evaluate=code=>window.webContents.executeJavaScript(code);
  const until=async code=>{const end=Date.now()+15000;while(!await evaluate(code)) {if(Date.now()>end) throw new Error('Intake renderer timed out: '+code+'\n'+await evaluate('document.body.innerText'));await new Promise(r=>setTimeout(r,50));}};
  const click=label=>evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(label)});if(!b||b.disabled)throw new Error('Missing button');b.click();})()`);
  const change=(label,value)=>evaluate(`(()=>{const s=document.querySelector('select[aria-label='+${JSON.stringify(JSON.stringify(label))}+']');if(!s)throw new Error('Missing select');s.value=${JSON.stringify(value)};s.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  const shot=async name=>{
    await evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
    const out=process.env.SUBSCRIBE_FLOW_VERIFY_OUTPUT||path.join(root,'docs/verification/m13');fs.mkdirSync(out,{recursive:true});
    fs.writeFileSync(path.join(out,name),(await window.webContents.capturePage()).toPNG());
  };
  const recognize=async url=>{
    await click('添加内容');await until(`!!document.querySelector('#intake-url')`);
    await evaluate(`(()=>{const i=document.querySelector('#intake-url');i.value=${JSON.stringify(url)};i.dispatchEvent(new Event('input',{bubbles:true}));})()`);
    await click('识别内容');
  };
  await until(`!!SF.app.state.session && !!document.querySelector('[data-view="inbox"] .state')`);
  assert.equal(await evaluate('SF.app.state.source'),'real');
  assert.equal(await evaluate('typeof require'),'undefined');
  assert.equal(await evaluate('SF.app.state.session.capabilities.canIntake'),true);
  const tag=await core.call('tag.create',{name:'M13 验收',color:'cyan'});
  await recognize(`https://m.bilibili.com/video/${fixture.bili.BVID}?p=2`);
  await until(`!!document.querySelector('.intake-preview')`);
  assert.equal((await core.call('content.list')).total,0,'预览不创建壳记录');
  assert.equal((await core.call('subscription.list')).length,0);
  await evaluate(`document.querySelector('[data-intake-priority="high"]').click()`);
  await evaluate(`document.querySelector('.dialog [data-tag-add]').click()`);
  await until(`!!document.querySelector('.tag-pool__chip')`);
  await evaluate(`document.querySelector('.tag-pool__chip').click()`);
  await click('确认挂载');
  await shot('m13-core-bili-preview.png');
  await click('保存内容');
  await until(`!document.querySelector('.dialog') && SF.app.state.counts.total===1 && !!document.querySelector('.content-card')`);
  const bili=(await core.call('content.list')).items[0];
  assert.equal(bili.intake_method,'manual');assert.equal(bili.tags[0].id,tag.id);assert.equal(bili.priority,'high');
  assert.equal(bili.published.value.slice(0,4),'2000');
  assert.ok(await evaluate(`document.querySelector('.detail').textContent.includes('原始发布') && document.querySelector('.detail').textContent.includes('添加于')`));
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('.detail button')).some(b=>b.textContent.trim()==='补充详情')`),false,'没有订阅的内容不提供依赖订阅的详情任务');
  await shot('m13-core-saved-inbox.png');
  const before=await core.call('content.get',{item_id:bili.id});
  const viewCount=fixture.bili.visits.filter(u=>u.endsWith('/view')).length;
  await recognize('https://b23.tv/fixture');
  await until(`!!document.querySelector('.intake-exists')`);
  assert.equal(fixture.bili.visits.filter(u=>u.endsWith('/view')).length,viewCount);
  await click('查看已有记录');
  await until(`!!document.querySelector('.dialog .detail-preview')`);
  await evaluate(`document.querySelector('.dialog [aria-label="关闭对话框"]').click()`);
  assert.deepEqual(await core.call('content.get',{item_id:bili.id}),before);
  const id=fixture.xhs.IDS[2]; // Unknown publication still enters today's calendar.
  await recognize(`https://www.xiaohongshu.com/discovery/item/${id}?source=webshare&xsec_source=pc_share&xsec_token=fixture-private-token`);
  await until(`!!document.querySelector('.intake-preview')`);
  assert.ok(await evaluate(`document.querySelector('.intake-preview').textContent.includes('发布时间未知')`));
  await evaluate(`SF.app.state.theme='dark';document.documentElement.dataset.theme='dark'`);
  await shot('m13-core-xhs-preview-dark.png');
  window.setSize(900,760);
  await shot('m13-core-preview-compact.png');
  assert.ok(await evaluate(`document.documentElement.scrollWidth<=innerWidth && document.querySelector('.dialog').getBoundingClientRect().bottom<=innerHeight`));
  window.setSize(1440,1000);
  await click('保存内容');
  await until(`!document.querySelector('.dialog') && SF.app.state.counts.total===2`);
  const sources=(await core.call('source.list')).items;
  assert.equal(sources.length,2);assert.equal((await core.call('subscription.list')).length,0);
  await change('筛选来源',sources.find(s=>s.channel==='xiaohongshu').id);
  await change('筛选收录方式','manual');
  await until(`document.querySelectorAll('.content-card').length===1 && document.querySelector('.content-card').dataset.contentId==='xiaohongshu:note:${id}'`);
  await change('筛选收录方式','subscription');
  await until(`document.querySelectorAll('.content-card').length===0 && !!document.querySelector('[data-view="inbox"] .state')`);
  await evaluate(`SF.app.state.filters={quick:'all',intakeMethod:'manual'};SF.app.navigate('overview',{mode:'calendar'});SF.app.refreshData(true)`);
  await until(`!!document.querySelector('.calendar-grid')`);await click('今天');
  await until(`document.querySelectorAll('[data-calendar-item]').length===2`);
  await change('日历来源',sources.find(s=>s.channel==='xiaohongshu').id);
  await until(`document.querySelectorAll('[data-calendar-item]').length===1`);
  assert.equal(await evaluate(`document.querySelector('[data-calendar-item]').dataset.calendarItem`),'xiaohongshu:note:'+id);
  await shot('m13-core-manual-calendar.png');
  await evaluate(`SF.app.navigate('overview',{mode:'priority'})`);
  await until(`document.body.innerText.includes('未设置 · 1')`);
  await click('未设置 · 1');
  await until(`document.querySelectorAll('[data-priority-item]').length===1`);
  await change('看板收录方式','subscription');
  await until(`document.querySelectorAll('[data-priority-item]').length===0`);
  await core.restart();
  assert.equal((await core.call('content.list',{intake_method:'manual'})).total,2);
  assert.equal((await core.call('subscription.list')).length,0);
  console.log(JSON.stringify({intakeRenderer:'passed',realBridge:true,realCore:true,realPlatform:false,previewNoWrite:true,duplicateNoOp:true,sourceWithoutSubscription:true,manualCalendar:true,filtersAcrossViews:true,restartPersisted:true}));
}
module.exports={verify};
